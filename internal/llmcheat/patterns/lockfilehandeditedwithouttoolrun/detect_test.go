// TestDetect_CleanYarnStyleHeader proves a realistic multi-line generator
// header that spans two DIFFERENT recognized disclaimer phrases (a
// "DO NOT EDIT" line followed by a short "lockfile vN" version tag line, as
// real yarn.lock files ship) is not flagged just because the second header
// line does not itself repeat a "generated" phrase.
func TestDetect_CleanYarnStyleHeader(t *testing.T) {
	const src = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0":
  version "7.22.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.22.0.tgz"
`
	d := detector{}
	got := d.Detect("yarn.lock", []byte(src))

	if len(got) != 0 {
		t.Fatalf("Detect() returned %d matches, want 0 for a genuine yarn.lock header; got %+v", len(got), got)
	}
}

