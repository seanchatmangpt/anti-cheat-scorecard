// TestDetect_DirtyPoetryLockAndLockToml proves the detector covers the
// other named filenames/suffixes from the spec (poetry.lock and a generic
// *.lock.toml file), each with a hand-authored mid-file comment.
func TestDetect_DirtyPoetryLockAndLockToml(t *testing.T) {
	const src = `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "requests"
version = "2.31.0"

# had to patch this in manually since poetry lock kept timing out on CI
[[package]]
name = "urllib3"
version = "2.0.4"
`

	cases := []struct {
		name string
		path string
	}{
		{"poetry.lock exact name", "poetry.lock"},
		{"generic .lock.toml suffix", "deps.lock.toml"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := detector{}
			got := d.Detect(tc.path, []byte(src))
			if len(got) != 1 {
				t.Fatalf("Detect(%q) returned %d matches, want exactly 1; got %+v", tc.path, len(got), got)
			}
			if got[0].Severity != llmcheat.SeverityMedium {
				t.Errorf("match Severity = %q, want %q", got[0].Severity, llmcheat.SeverityMedium)
			}
		})
	}
}

