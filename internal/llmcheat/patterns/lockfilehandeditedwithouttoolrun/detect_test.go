// TestDetect_NonLockfileIgnored proves the detector only inspects files
// whose path matches one of the named lockfile patterns, even when the
// content contains the exact dirty comment text.
func TestDetect_NonLockfileIgnored(t *testing.T) {
	const src = "# regenerated by hand because ggen sync failed, do not overwrite\n[[package]]\n"

	d := detector{}
	got := d.Detect("notes.md", []byte(src))

	if len(got) != 0 {
		t.Fatalf("Detect() returned %d matches for a non-lockfile path, want 0; got %+v", len(got), got)
	}

	// Sanity check: the identical content at a real lockfile path IS
	// flagged, so the zero-match result above is really the path filter at
	// work and not some other bug silently swallowing the match.
	got2 := d.Detect("Cargo.lock", []byte(src))
	if len(got2) < 1 {
		t.Fatalf("Detect() returned %d matches for the equivalent Cargo.lock path, want at least 1", len(got2))
	}
}

// TestID_Category proves the detector reports the exact ID/Category
// contract this pattern was assigned.
func TestID_Category(t *testing.T) {
	d := detector{}
	if got := d.ID(); got != "lockfile-hand-edited-without-tool-run" {
		t.Errorf("ID() = %q, want %q", got, "lockfile-hand-edited-without-tool-run")
	}
	if got := d.Category(); got != "generated-artifact-tampering" {
		t.Errorf("Category() = %q, want %q", got, "generated-artifact-tampering")
	}
}
