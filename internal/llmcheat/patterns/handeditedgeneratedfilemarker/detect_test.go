func TestPattern_IDAndCategory(t *testing.T) {
	d := detector{}

	if got := d.ID(); got != patternID {
		t.Errorf("ID() = %q, want %q", got, patternID)
	}
	if got := d.Category(); got != patternCategory {
		t.Errorf("Category() = %q, want %q", got, patternCategory)
	}
	if got := d.ID(); got != "hand-edited-generated-file-marker" {
		t.Errorf("ID() = %q, want the literal spec ID %q", got, "hand-edited-generated-file-marker")
	}
	if got := d.Category(); got != "generated-artifact-tampering" {
		t.Errorf("Category() = %q, want the literal spec Category %q", got, "generated-artifact-tampering")
	}
}
