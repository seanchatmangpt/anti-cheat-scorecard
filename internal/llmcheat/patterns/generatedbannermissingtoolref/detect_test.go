// TestDetect_BareKnownToolNameAllowlisted proves a banner that names a
// recognizable generator token (no "by"/"via"/backtick needed) is treated
// as labeled -- covering the "known-tool-looking token like
// protoc/mockgen/sqlc/ggen/codegen" branch of the description directly.
func TestDetect_BareKnownToolNameAllowlisted(t *testing.T) {
	tests := []struct {
		name    string
		content string
	}{
		{"ggen", "// @generated ggen v1.2.0\n\npackage ontology\n"},
		{"sqlc", "// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n"},
		{"mockgen", "// AUTO-GENERATED via mockgen -source=widget.go\n\npackage mocks\n"},
	}

	d := detector{}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			matches := d.Detect("generated.go", []byte(tt.content))
			if len(matches) != 0 {
				t.Errorf("Detect() returned %d matches for a %s-labeled banner, want 0: %+v", len(matches), tt.name, matches)
			}
		})
	}
}

// TestDetect_BannerOutsideFirstFiveLines_ProducesNoMatches proves the
// pattern respects its own stated scope: a generated-file claim that first
// appears after line 5 (e.g. buried under a long license header) is out of
// the banner window entirely and is not flagged.
func TestDetect_BannerOutsideFirstFiveLines_ProducesNoMatches(t *testing.T) {
	content := []byte(`// Copyright 2026 Example Corp.
//
// Licensed under the Apache License, Version 2.0.
// See LICENSE for details.
// Additional header padding line.
// AUTO-GENERATED FILE. DO NOT EDIT.

package widget
`)

	d := detector{}
	matches := d.Detect("pkg/widget/widget.go", content)

	if len(matches) != 0 {
		t.Fatalf("Detect() returned %d matches, want 0 for a banner starting at line 6 (outside the first %d lines): %+v",
			len(matches), maxBannerLines, matches)
	}
}

// TestDetect_NoGeneratedClaim_ProducesNoMatches proves ordinary
// hand-written source with no generated-file claim at all is never
// flagged.
func TestDetect_NoGeneratedClaim_ProducesNoMatches(t *testing.T) {
	content := []byte(`// Package widget implements the widget domain type.
package widget

// Widget is a named, identified widget.
type Widget struct {
	Name string
	ID   int64
}
`)

	d := detector{}
	matches := d.Detect("pkg/widget/widget.go", content)

	if len(matches) != 0 {
		t.Fatalf("Detect() returned %d matches, want 0 for hand-written source with no generated banner: %+v", len(matches), matches)
	}
}

// TestDetect_ImplementsPatternInterface is a compile-time-flavored check
// that detector really satisfies llmcheat.Pattern and reports the expected
// ID/Category via the real interface methods (not just the concrete type).
func TestDetect_ImplementsPatternInterface(t *testing.T) {
	var p llmcheat.Pattern = detector{}
	if p.ID() != "generated-banner-missing-tool-reference" {
		t.Errorf("ID() = %q, want %q", p.ID(), "generated-banner-missing-tool-reference")
	}
	if p.Category() != "generated-artifact-tampering" {
		t.Errorf("Category() = %q, want %q", p.Category(), "generated-artifact-tampering")
	}
}
