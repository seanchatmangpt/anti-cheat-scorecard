// TestDetect_UnlabeledAutoGeneratedBanner_ProducesMatch exercises the exact
// dirty shape from the task description, expanded into a realistic
// generated-looking Go file: an "AUTO-GENERATED FILE. DO NOT EDIT." banner
// that never says what produced the file.
func TestDetect_UnlabeledAutoGeneratedBanner_ProducesMatch(t *testing.T) {
	content := []byte(`// AUTO-GENERATED FILE. DO NOT EDIT.

package widgetpb

type Widget struct {
	Name string
	ID   int64
}
`)

	d := detector{}
	matches := d.Detect("pkg/widgetpb/widget.pb.go", content)

	if len(matches) < 1 {
		t.Fatalf("Detect() returned %d matches, want at least 1 for an unlabeled AUTO-GENERATED banner", len(matches))
	}
	for _, m := range matches {
		if m.PatternID != "generated-banner-missing-tool-reference" {
			t.Errorf("Match.PatternID = %q, want %q", m.PatternID, "generated-banner-missing-tool-reference")
		}
		if m.Category != "generated-artifact-tampering" {
			t.Errorf("Match.Category = %q, want %q", m.Category, "generated-artifact-tampering")
		}
	}
	if matches[0].Line != 1 {
		t.Errorf("Match.Line = %d, want 1 (the banner line)", matches[0].Line)
	}
}

// TestDetect_ProtocBannerWithByClause_ProducesNoMatches proves the exact
// clean shape from the task description -- a real protoc-gen-go-grpc
// banner that names its tool via "by" -- produces zero matches.
func TestDetect_ProtocBannerWithByClause_ProducesNoMatches(t *testing.T) {
	content := []byte(`// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
// versions:
// - protoc-gen-go-grpc v1.3.0
// source: widget.proto

package widgetpb
`)

	d := detector{}
	matches := d.Detect("pkg/widgetpb/widget_grpc.pb.go", content)

	if len(matches) != 0 {
		t.Fatalf("Detect() returned %d matches, want 0 for a properly-labeled protoc banner: %+v", len(matches), matches)
	}
}

